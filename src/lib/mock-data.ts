function generateMomentum(seed: number, maxMin: number, events: { min: number; type: MomentumPoint['event'] }[]): MomentumPoint[] {
  const points: MomentumPoint[] = [];
  let prev = 0;
  for (let m = 1; m <= maxMin; m++) {
    const wave = Math.sin((m + seed) * 0.28) * 52 + Math.cos((m * 1.7 + seed) * 0.19) * 34;
    const smoothed = Math.max(-95, Math.min(95, Math.round(prev * 0.35 + wave * 0.65)));
    prev = smoothed;
    const ev = events.find((e) => e.min === m);
    points.push({
      minute: m,
      value: ev?.type === 'goal-home' ? 88 : ev?.type === 'goal-away' ? -88 : smoothed,
      event: ev?.type,
    });
  }
  return points;
}

